"""Convenience shapes for SageMaker Processing jobs."""

from typing import Optional

from sagemaker.core.helper.pipeline_variable import BoolPipeVar, StrPipeVar
from sagemaker.core.shapes.shapes import (
    DatasetDefinition,
    ProcessingInput as _ProcessingInput,
    ProcessingS3Input,
)
from sagemaker.core.utils.utils import Unassigned


class ProcessingInput(_ProcessingInput):
    """Configure an input for a SageMaker Processing job.

    ``source`` and ``destination`` provide the convenient v2-style interface. A local
    ``source`` is uploaded to S3 when the processor normalizes its inputs. Callers can
    alternatively supply the service-level ``s3_input`` or ``dataset_definition`` shape.

    Args:
        source: Local path or S3 URI containing the input data.
        destination: Absolute path where the input is made available in the container.
        input_name: Name of the processing input. Generated by the processor when omitted.
        s3_data_type: How SageMaker interprets the S3 data, such as ``S3Prefix``.
        s3_input_mode: How data is made available to the container, such as ``File``.
        s3_data_distribution_type: How data is distributed across processing instances.
        s3_compression_type: Compression format of the input data.
        app_managed: Whether the processing application manages input operations.
        s3_input: Service-level S3 input configuration. Mutually exclusive with ``source``.
        dataset_definition: Athena or Redshift dataset configuration.
    """

    input_name: Optional[StrPipeVar] = None

    def __init__(
        self,
        *,
        source: Optional[StrPipeVar] = None,
        destination: Optional[StrPipeVar] = None,
        input_name: Optional[StrPipeVar] = None,
        s3_data_type: StrPipeVar = "S3Prefix",
        s3_input_mode: StrPipeVar = "File",
        s3_data_distribution_type: StrPipeVar = "FullyReplicated",
        s3_compression_type: StrPipeVar = "None",
        app_managed: Optional[BoolPipeVar] = Unassigned(),
        s3_input: Optional[ProcessingS3Input] = Unassigned(),
        dataset_definition: Optional[DatasetDefinition] = Unassigned(),
    ):
        if source is not None and s3_input:
            raise ValueError("source and s3_input are mutually exclusive")
        if source is not None and destination is None:
            raise ValueError("destination is required when source is provided")

        if source is not None:
            s3_input = ProcessingS3Input(
                s3_uri=source,
                local_path=destination,
                s3_data_type=s3_data_type,
                s3_input_mode=s3_input_mode,
                s3_data_distribution_type=s3_data_distribution_type,
                s3_compression_type=s3_compression_type,
            )

        input_config = {"input_name": input_name}
        if not isinstance(app_managed, Unassigned):
            input_config["app_managed"] = app_managed
        if not isinstance(s3_input, Unassigned):
            input_config["s3_input"] = s3_input
        if not isinstance(dataset_definition, Unassigned):
            input_config["dataset_definition"] = dataset_definition

        super().__init__(**input_config)

    @property
    def source(self):
        """Return the configured local path or S3 URI."""
        return self.s3_input.s3_uri if self.s3_input else None

    @property
    def destination(self):
        """Return the configured destination path in the processing container."""
        return self.s3_input.local_path if self.s3_input else None
